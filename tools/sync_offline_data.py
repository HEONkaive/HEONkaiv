#!/usr/bin/env python3
"""Build script-loadable data mirrors from the canonical HEON ARCHIVE JSON files.

Run from any directory: python tools/sync_offline_data.py
This lets index.html work via file:// (where fetch(JSON) can be blocked).
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def create_mirror(src: Path, output: Path, js_slot: str) -> None:
    obj = json.loads(src.read_text(encoding='utf-8'))
    body = json.dumps(obj, ensure_ascii=False, separators=(',', ':'))
    prefix = ('/* Auto-generated by tools/sync_offline_data.py — edit the corresponding JSON, not this file. */\n'
              'window.HEON_ARCHIVE_DATA = window.HEON_ARCHIVE_DATA || {professors:{}};\n')
    output.write_text(prefix + f'window.HEON_ARCHIVE_DATA.{js_slot} = {body};\n', encoding='utf-8')
    print(f'Updated {output.relative_to(ROOT)}')

catalog = json.loads((ROOT / 'data/catalog.json').read_text(encoding='utf-8'))
create_mirror(ROOT / 'data/catalog.json', ROOT / 'data/catalog.js', 'catalog')
seen = set()
for subject in catalog['subjects']:
    for prof in subject.get('professors', []):
        if prof['id'] in seen:
            raise ValueError(f'Duplicate professor ID: {prof["id"]}')
        seen.add(prof['id'])
        src = ROOT / prof['data']
        if not src.is_file():
            raise FileNotFoundError(src)
        obj = json.loads(src.read_text(encoding='utf-8'))
        if obj['professor']['id'] != prof['id']:
            raise ValueError(f'Professor ID mismatch: {src}')
        body = json.dumps(obj, ensure_ascii=False, separators=(',', ':'))
        dest = src.with_suffix('.js')
        dest.write_text(
            '/* Auto-generated offline-compatible question data — do not edit directly. */\n'
            'window.HEON_ARCHIVE_DATA = window.HEON_ARCHIVE_DATA || {professors:{}};\n'
            'window.HEON_ARCHIVE_DATA.professors = window.HEON_ARCHIVE_DATA.professors || {};\n'
            f'window.HEON_ARCHIVE_DATA.professors[{json.dumps(prof["id"])}] = {body};\n',
            encoding='utf-8'
        )
        print(f'Updated {dest.relative_to(ROOT)} ({len(obj["questions"])} questions)')
